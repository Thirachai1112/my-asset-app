create or replace function public.create_office_equipment_loans(
  p_equipment_ids bigint[],
  p_borrower_name text,
  p_borrower_emp_id text,
  p_borrower_contact text,
  p_due_date date,
  p_notes text,
  p_batch_id text
)
returns setof public.officeequipmentloans
language plpgsql
security definer
set search_path = public
as $$
declare
  v_equipment_id bigint;
  v_found_count bigint;
begin
  if coalesce(cardinality(p_equipment_ids), 0) = 0 then
    raise exception 'equipment_ids array is required and must not be empty';
  end if;

  if cardinality(p_equipment_ids) <> (
    select count(distinct equipment_id)
    from unnest(p_equipment_ids) as ids(equipment_id)
  ) then
    raise exception 'Duplicate equipment IDs are not allowed';
  end if;

  perform 1
  from public.officeequipments
  where id = any(p_equipment_ids)
  order by id
  for update;

  select count(*) into v_found_count
  from public.officeequipments
  where id = any(p_equipment_ids);

  if v_found_count <> cardinality(p_equipment_ids) then
    raise exception 'One or more equipment IDs were not found';
  end if;

  if exists (
    select 1
    from public.officeequipments
    where id = any(p_equipment_ids) and status = 'ถูกยืม'
  ) or exists (
    select 1
    from public.officeequipmentloans
    where equipment_id = any(p_equipment_ids) and returned_at is null
  ) then
    raise exception 'One or more items already have active loan records';
  end if;

  foreach v_equipment_id in array p_equipment_ids loop
    insert into public.officeequipmentloans (
      equipment_id, borrower_name, borrower_emp_id, borrower_contact,
      due_date, notes, batch_id
    ) values (
      v_equipment_id, p_borrower_name, p_borrower_emp_id, p_borrower_contact,
      p_due_date, p_notes, p_batch_id
    );

    update public.officeequipments
    set status = 'ถูกยืม'
    where id = v_equipment_id;

    insert into public.officeequipmentauditlogs (
      action_type, target_table, target_id, notes
    ) values (
      'BORROW', 'officeequipments', v_equipment_id,
      format('Borrowed by %s under batch %s', p_borrower_name, p_batch_id)
    );
  end loop;

  return query
  select *
  from public.officeequipmentloans
  where batch_id = p_batch_id
  order by id;
end;
$$;

create or replace function public.return_office_equipment(
  p_equipment_id bigint,
  p_notes text default null
)
returns setof public.officeequipmentloans
language plpgsql
security definer
set search_path = public
as $$
declare
  v_open_loan public.officeequipmentloans%rowtype;
begin
  perform 1
  from public.officeequipments
  where id = p_equipment_id
  for update;

  select *
  into v_open_loan
  from public.officeequipmentloans
  where equipment_id = p_equipment_id and returned_at is null
  order by borrowed_at desc
  limit 1
  for update;

  if not found then
    raise exception 'Equipment is not currently marked as borrowed (no active loan record found)';
  end if;

  update public.officeequipmentloans
  set returned_at = now(),
      notes = case
        when p_notes is null or p_notes = '' then v_open_loan.notes
        else concat(coalesce(v_open_loan.notes, ''), E'\nReturn Note: ', p_notes)
      end
  where id = v_open_loan.id
  returning * into v_open_loan;

  update public.officeequipments
  set status = 'ใช้งาน'
  where id = p_equipment_id;

  insert into public.officeequipmentauditlogs (
    action_type, target_table, target_id, notes
  ) values (
    'RETURN', 'officeequipments', p_equipment_id,
    format('Returned loan ID: %s', v_open_loan.id)
  );

  return next v_open_loan;
end;
$$;

