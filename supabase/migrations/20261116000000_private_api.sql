create table if not exists public.peajobs (
  id bigint generated by default as identity primary key,
  pea_site_id integer not null,
  job_name text not null,
  job_description text,
  job_type text,
  priority text default 'ปกติ',
  department text,
  requester_name text,
  requester_emp_id text,
  requester_contact text,
  notification_doc_no text,
  equipment_ids jsonb,
  problem_equipment_ids jsonb,
  budget_transaction_ids jsonb,
  status text default 'เปิดงาน',
  user_id integer,
  user_name text default 'Unknown',
  created_at timestamptz not null default now(),
  updated_at timestamptz not null default now(),
  constraint peajobs_site_job_name_key unique (pea_site_id, job_name)
);

create table if not exists public.officeequipments (
  id bigint generated by default as identity primary key,
  name text not null,
  ip_address varchar(45),
  mac_address varchar(45),
  department text,
  pea_site_id integer,
  equipment_type text,
  status text default 'ใช้งาน',
  notes text,
  contract_no text,
  contract_start_date date,
  contract_expiry_date date,
  vendor text,
  serial_number text,
  asset_number text,
  asset_owner text,
  asset_owner_emp_id text,
  storage_location text,
  created_at timestamptz not null default now(),
  updated_at timestamptz not null default now(),
  constraint officeequipments_ip_address_key unique (ip_address),
  constraint officeequipments_mac_address_key unique (mac_address),
  constraint officeequipments_serial_number_key unique (serial_number),
  constraint officeequipments_asset_number_key unique (asset_number)
